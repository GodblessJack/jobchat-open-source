// jchat/server/storage/local-files.ts
//
// Local filesystem storage replacing Supabase Storage.
// - Multer-based file upload via POST /api/files/upload
// - Static serve via /files/*
// - Path construction helpers for file URLs
//
// Files are stored under config.filesRoot/<userId>/<uuid>.<ext> and served
// at /files/<userId>/<uuid>.<ext>.

import path from 'node:path';
import fs from 'node:fs/promises';
import multer, { MulterError } from 'multer';
import express, { Router } from 'express';
import rateLimit from 'express-rate-limit';
import { randomUUID as uuid } from 'node:crypto';
import { verifyJchatJwt } from '../auth/jwt-verify';
import { verifyAccessToken } from '../auth/local-jwt';
import { signedDownloadUrl } from './signed-url';
import { config } from '../config';
import { logger } from '../logger';

const FILES_ROOT = path.resolve(config.filesRoot);

// Sanitise to prevent stored-XSS: only allow file extensions that browsers
// won't execute as scripts. SVG is deliberately excluded (scriptable).
const ALLOWED_EXTENSIONS = new Set([
  '.jpg', '.jpeg', '.png', '.gif', '.webp', '.bmp',
  '.pdf', '.doc', '.docx', '.xls', '.xlsx', '.ppt', '.pptx',
  '.txt', '.csv', '.md', '.json', '.xml',
  '.mp3', '.mp4', '.mov', '.avi', '.webm',
  '.zip', '.tar', '.gz', '.7z',
]);

// Ensure upload directory exists (best-effort — multer will fail later if
// the directory doesn't exist, but this avoids the race on first upload).
fs.mkdir(FILES_ROOT, { recursive: true }).catch(() => {});

const diskStorage = multer.diskStorage({
  destination: async (_req, _file, cb) => {
    const userId = (_req as any).userId || 'anonymous';
    const userDir = path.join(FILES_ROOT, userId);
    await fs.mkdir(userDir, { recursive: true });
    cb(null, userDir);
  },
  filename: (_req, file, cb) => {
    const ext = path.extname(file.originalname).toLowerCase();
    if (!ALLOWED_EXTENSIONS.has(ext)) {
      cb(new Error(`File type not allowed: ${ext || 'unknown'}`), '');
      return;
    }
    cb(null, `${uuid()}${ext}`);
  },
});

export const upload = multer({
  storage: diskStorage,
  limits: { fileSize: config.uploadMaxSize },
});

// Rate limiters for file upload endpoints (defence against upload-flood DoS).
const isDev = config.nodeEnv !== 'production';
const uploadLimiter = rateLimit({
  windowMs: 60 * 1000,   // 1 minute
  max: isDev ? 200 : 10,  // generous in dev, tight in prod
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: 'RATE_LIMITED', message: 'Too many upload requests. Try again later.' },
});
const putLimiter = rateLimit({
  windowMs: 60 * 1000,
  max: isDev ? 200 : 20,  // PUT is used for local-fs fallback; a bit more generous
  standardHeaders: true,
  legacyHeaders: false,
  message: { error: 'RATE_LIMITED', message: 'Too many upload requests. Try again later.' },
});

// Request body timeout for the PUT endpoint (defence against slow-loris uploads).
const PUT_TIMEOUT_MS = 120_000;

export function mountFileRoutes(app: Router) {
  // Stored-XSS defence-in-depth: force Content-Disposition: attachment for
  // potentially executable types (HTML, SVG) so the browser never runs them
  // as scripts. For images and other safe types, let the browser decide
  // (inline display for images, download prompt for PDFs based on user prefs).
  const XSS_DANGEROUS_EXT = new Set([
    '.html', '.htm', '.svg', '.xml',
  ]);
  // Image/video/audio extensions safe for inline browser rendering.
  // Browsers cannot attach Authorization headers to <img>/<video>/<audio>
  // element requests, so these types are served without auth.
  const SAFE_INLINE_EXTS = new Set([
    '.jpg', '.jpeg', '.png', '.gif', '.webp', '.bmp',
    '.mp4', '.webm', '.mov', '.avi',
    '.mp3', '.wav', '.ogg',
  ]);
  // Auth middleware: verify JWT from Authorization header or ?token= query param.
  // Inline content (<img>, <video>) can't set headers, so the query-string path
  // supports short-lived signed download tokens generated by signedDownloadUrl().
  app.use('/files', (req, res, next) => {
    // Reject path traversal before any auth check. Decode first — %2e%2e
    // bypasses a literal '..' substring check but express.static decodes
    // and normalizes it afterward.
    try {
      if (decodeURIComponent(req.path).includes('..')) {
        return res.status(403).json({ error: 'AUTH_FORBIDDEN' });
      }
    } catch {
      return res.status(400).json({ error: 'VALIDATION_ERROR' });
    }
    // Check Authorization header first.
    const authHeader = req.headers.authorization;
    if (authHeader) {
      const rawToken = authHeader.startsWith('Bearer ') ? authHeader.slice(7) : authHeader;
      verifyJchatJwt(rawToken)
        .then((user) => {
          // Enforce ownership: Bearer-authenticated users can only access
          // files they own. Paths are either /<userId>/... (POST /api/files/upload)
          // or /jchat/<userId>/... (signed-url uploadInit).
          const segments = req.path.split('/').filter(Boolean);
          const ownerId = segments[0] === 'jchat' ? segments[1] : segments[0];
          if (!ownerId || ownerId !== user.id) {
            return res.status(403).json({ error: 'AUTH_FORBIDDEN' });
          }
          next();
        })
        .catch(() => res.status(401).json({ error: 'AUTH_INVALID' }));
      return;
    }
    // Fall back to ?token= query param (signed short-lived download token).
    const qToken = typeof req.query.token === 'string' ? req.query.token : null;
    if (qToken) {
      verifyAccessToken(qToken)
        .then((p) => {
          if ((p as any).purpose !== 'download') throw new Error('wrong purpose');
          // Token's filePath must match the requested path (prevent cross-file access).
          const expected = (p as any).filePath as string | undefined;
          if (expected && req.path !== `/${expected}`) {
            return res.status(403).json({ error: 'token path mismatch' });
          }
          next();
        })
        .catch(() => res.status(401).json({ error: 'AUTH_INVALID' }));
      return;
    }
    // Public access for safe image types: browsers cannot attach Authorization
    // headers to <img> / <video> requests, so inline media must be accessible
    // without auth. Documents and other types require a signed ?token= or
    // Bearer header (see signedDownloadUrl).
    const ext = path.extname(req.path).toLowerCase();
    if (SAFE_INLINE_EXTS.has(ext)) {
      next();
      return;
    }
    res.status(401).json({ error: 'AUTH_REQUIRED' });
  }, (req, res, next) => {
    // Content-Disposition: attachment for XSS-dangerous extensions
    const ext = path.extname(req.path).toLowerCase();
    if (XSS_DANGEROUS_EXT.has(ext)) {
      res.setHeader('Content-Disposition', 'attachment');
    }
    next();
  }, express.static(FILES_ROOT));

  // Upload endpoint (requires auth + rate limit)
  app.post('/api/files/upload', uploadLimiter, async (req, res, next) => {
    try {
      const authHeader = req.headers.authorization;
      if (!authHeader) {
        res.status(401).json({ error: 'AUTH_REQUIRED' });
        return;
      }
      const token = authHeader.slice(7);
      const user = await verifyJchatJwt(token);
      (req as any).userId = user.id;
    } catch {
      res.status(401).json({ error: 'AUTH_INVALID' });
      return;
    }
    next();
  }, upload.single('file'), (req, res) => {
    const file = (req as any).file;
    if (!file) {
      res.status(400).json({ error: 'No file uploaded' });
      return;
    }
    const userId = (req as any).userId;
    const relativePath = `/${userId}/${file.filename}`;
    res.json({
      path: `/files${relativePath}`,
      filename: file.originalname,
      size: file.size,
    });
  });

  // PUT endpoint for local file uploads (used by signed-url.ts fallback when
  // Supabase Storage is not configured). The client PUTs raw file bytes with a
  // short-lived JWT in the query string that encodes the target file path.
  app.put('/api/files/put', putLimiter, async (req, res) => {
    try {
      const token = typeof req.query.token === 'string' ? req.query.token : null;
      if (!token) {
        res.status(401).json({ error: 'Missing upload token' });
        return;
      }
      // Verify the upload token — it's an access-type JWT with a custom payload.
      let payload: { sub: string; filePath: string; purpose: string };
      try {
        const verified = await verifyAccessToken(token);
        if ((verified as any).purpose !== 'upload') throw new Error('Wrong token purpose');
        payload = verified as unknown as typeof payload;
      } catch {
        res.status(401).json({ error: 'Invalid upload token' });
        return;
      }
      // Security: filePath must start with jchat/<userId>/ (prevents cross-user
      // writes). Then resolve and verify the result stays within FILES_ROOT
      // (defence-in-depth against ../ path traversal).
      if (!payload.filePath || !payload.filePath.startsWith(`jchat/${payload.sub}/`)) {
        res.status(403).json({ error: 'Invalid file path' });
        return;
      }
      const targetPath = path.resolve(FILES_ROOT, payload.filePath);
      if (!targetPath.startsWith(FILES_ROOT + path.sep)) {
        res.status(403).json({ error: 'Invalid file path' });
        return;
      }
      // Validate content-length before reading body.
      // parseInt with an invalid header returns NaN — guard against that so
      // the NaN-is-not-<=-0 quirk of JS doesn't silently skip the check.
      const rawLen = parseInt(req.headers['content-length'] || '', 10);
      if (!Number.isFinite(rawLen) || rawLen <= 0) {
        res.status(400).json({ error: 'Missing or invalid Content-Length' });
        return;
      }
      const contentLength = rawLen;
      if (contentLength > config.uploadMaxSize) {
        res.status(413).json({ error: 'File too large', maxSize: config.uploadMaxSize });
        return;
      }
      // Collect body chunks with size limit and a hard timeout so a
      // slow-loris upload (1 byte per minute) cannot hold the connection and
      // buffer indefinitely.
      await fs.mkdir(path.dirname(targetPath), { recursive: true });
      const chunks: Buffer[] = [];
      let totalBytes = 0;
      const bodyTimer = setTimeout(() => {
        if (!req.destroyed) req.destroy(new Error('Upload body timed out'));
      }, PUT_TIMEOUT_MS);
      req.on('data', (chunk: Buffer) => {
        totalBytes += chunk.length;
        if (totalBytes > config.uploadMaxSize) {
          clearTimeout(bodyTimer);
          req.destroy(new Error('File too large'));
          return;
        }
        chunks.push(chunk);
      });
      await new Promise<void>((resolve, reject) => {
        req.on('end', async () => {
          clearTimeout(bodyTimer);
          try {
            await fs.writeFile(targetPath, Buffer.concat(chunks));
            resolve();
          } catch (err) {
            reject(err);
          }
        });
        req.on('error', (err) => {
          clearTimeout(bodyTimer);
          reject(err);
        });
      });
      logger.info({ filePath: payload.filePath, size: Buffer.concat(chunks).length }, 'Local file PUT succeeded');
      res.status(200).json({ ok: true, path: `/${payload.filePath}` });
    } catch (err: any) {
      if (err?.message === 'File too large' || err?.message === 'Upload body timed out') {
        res.status(413).json({ error: 'File too large', maxSize: config.uploadMaxSize });
        return;
      }
      logger.error({ err }, 'Local file PUT failed');
      res.status(500).json({ error: 'Upload failed' });
    }
  });

  // Multer error handler — catches MulterError (e.g. file too large) and
  // extension validation errors, returning proper HTTP status codes.

  // REST endpoint for signed download URLs.
  // FileCard uses this when WebSocket is unavailable or the ws command fails.
  // Requires Bearer auth; returns a short-lived signed URL the client can open.
  app.get('/api/files/signed-download-url', async (req, res) => {
    try {
      const authHeader = req.headers.authorization;
      if (!authHeader) {
        res.status(401).json({ error: 'AUTH_REQUIRED' });
        return;
      }
      const token = authHeader.startsWith('Bearer ') ? authHeader.slice(7) : authHeader;
      const user = await verifyJchatJwt(token); // throws on invalid token
      let filePath = typeof req.query.filePath === 'string' ? req.query.filePath : null;
      if (!filePath) {
        res.status(400).json({ error: 'VALIDATION_ERROR', message: 'filePath is required' });
        return;
      }
      // Normalize path: HTTP upload uses /files/<userId>/<uuid>.ext (no jchat/ prefix),
      // while WebSocket/agent uploads use jchat/<userId>/<convId>/<uuid>-<name>.ext.
      // Accept both conventions by prepending jchat/ if missing.
      if (!filePath.startsWith('jchat/')) {
        filePath = filePath.replace(/^\/+/, '');
        if (/^[a-f0-9-]{36}\//.test(filePath)) {
          filePath = `jchat/${filePath}`;
        } else {
          res.status(400).json({ error: 'VALIDATION_ERROR', message: 'filePath must start with jchat/ or <userId>/' });
          return;
        }
      }
      // Ownership check: user can only request signed URLs for their own files
      if (!filePath.startsWith(`jchat/${user.id}/`)) {
        res.status(403).json({ error: 'AUTH_FORBIDDEN' });
        return;
      }
      const result = await signedDownloadUrl(filePath);
      res.json(result);
    } catch {
      res.status(401).json({ error: 'AUTH_INVALID' });
    }
  });
  app.use((err: unknown, _req: express.Request, res: express.Response, next: express.NextFunction) => {
    if (err instanceof MulterError) {
      if (err.code === 'LIMIT_FILE_SIZE') {
        res.status(413).json({ error: 'File too large', maxSize: config.uploadMaxSize });
        return;
      }
      res.status(400).json({ error: err.message, code: err.code });
      return;
    }
    if (err instanceof Error && err.message.startsWith('File type not allowed:')) {
      res.status(400).json({ error: err.message });
      return;
    }
    next(err);
  });
}
